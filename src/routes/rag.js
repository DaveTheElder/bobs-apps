// src/routes/rag.js — RAG API (index / status / query / reindex / delete).
// All Python work goes through rag/cli.py with argv — no inline `python3 -c` strings,
// no shell-escaping bugs. Timeouts are generous: the local model spends ~50s on
// reasoning before first token, so a 60s ceiling was just barely failing.

