// src/routes/slideshows.js — Photo Slideshow API (see docs/archive/SLIDESHOW_PLAN.md).
// Shows + ordered photos live in SQLite; image files on disk named <uuid>.<ext>
// so two uploads can never collide or path-escape. Uploads are raw bytes
// (docs.js pattern): Content-Type decides the extension, a Transform stream
// enforces the size cap mid-flight instead of after the disk already ate it.
// Audio: music_url is a YouTube link the SERVER renders to local files via
// yt-dlp (src/audio.js) — embeds are dead on bare-IP origins (Error 153).

