// ==================== GEO MATH (pure, module scope) ====================
const EARTH_R = 6371000; // m

/** Great-circle distance between two {lat,lng} fixes, in meters. */
export function haversine(a, b) {
  const toRad = (d) => (d * Math.PI) / 180;
  const dLat = toRad(b.lat - a.lat);
  const dLng = toRad(b.lng - a.lng);
  const s =
    Math.sin(dLat / 2) ** 2 +
    Math.cos(toRad(a.lat)) * Math.cos(toRad(b.lat)) * Math.sin(dLng / 2) ** 2;
  return 2 * EARTH_R * Math.asin(Math.sqrt(s));
}

/** Summed polyline distance over ordered points, meters (0/1 points → 0). */
export function pathLength(points) {
  let d = 0;
  for (let i = 1; i < points.length; i++) d += haversine(points[i - 1], points[i]);
  return d;
}

/** Polygon area (shoelace on a local equirectangular projection), m².
 *  Backyard-scale error is well under GPS noise; no need for geodesics. */
export function polygonArea(points) {
  if (points.length < 3) return 0;
  const p0 = points[0];
  const kx = Math.cos((p0.lat * Math.PI) / 180) * 111320; // m per deg lng
  const ky = 110540; // m per deg lat
  const xy = points.map((p) => [(p.lng - p0.lng) * kx, (p.lat - p0.lat) * ky]);
  let a = 0;
  for (let i = 0; i < xy.length; i++) {
    const [x1, y1] = xy[i];
    const [x2, y2] = xy[(i + 1) % xy.length];
    a += x1 * y2 - x2 * y1;
  }
  return Math.abs(a) / 2;
}

// ==================== DISPLAY HELPERS ====================
const M_TO_FT = 3.28084;

function fmtDist(m) {
  if (m == null || !Number.isFinite(m)) return '—';
  const ft = m * M_TO_FT;
  return ft >= 5280 ? `${(ft / 5280).toFixed(2)} mi (${m.toFixed(0)} m)`
                     : `${ft.toFixed(1)} ft (${m.toFixed(1)} m)`;
}

function fmtArea(m2) {
  if (!m2) return '—';
  const ft2 = m2 * M_TO_FT * M_TO_FT;
  const acres = ft2 / 43560;
  return `${ft2.toFixed(0)} ft² (${acres >= 0.1 ? acres.toFixed(2) + ' acres, ' : ''}${m2.toFixed(0)} m²)`;
}

function accClass(acc) {
  if (acc == null) return 'none';
  if (acc <= 8) return 'good';
  if (acc <= 20) return 'fair';
  return 'poor';
}

// ==================== GPS STATUS PANEL ====================
function GpsNotice({ supported, secure, error }) {
  if (!supported)
    return <div className="notice bad">This browser has no geolocation API at all.</div>;
  if (!secure)
    return (
      <div className="notice warn">
        <strong>GPS is blocked here.</strong> Phones only hand out location over
        HTTPS (or localhost) — this site is plain HTTP on the LAN. Two fixes:
        <ol>
          <li>
            Quick: in Chrome on the phone open{' '}
            <code>chrome://flags/#unsafely-treat-insecure-origin-as-secure</code>,
            paste <code>http://&lt;your-lan-ip&gt;</code>, enable, restart Chrome.
          </li>
          <li>Proper: put HTTPS (Caddy internal CA) on the homelab and trust the
            root cert on the phone.</li>
        </ol>
        Points below were saved by a device that had GPS.
      </div>
    );
  if (error)
    return (
      <div className="notice bad">
        GPS error: {error}. Check the location permission for this site and
        make sure it isn't indoors — phone GPS needs sky.
      </div>
    );
  return null;
}

// ==================== CANVAS PLOT ====================
function Plot({ points, fix, closed }) {
  const ref = useRef(null);

  useEffect(() => {
    const canvas = ref.current;
    if (!canvas) return;
    const dpr = window.devicePixelRatio || 1;
    const cssW = canvas.clientWidth;
    const cssH = canvas.clientHeight;
    canvas.width = cssW * dpr;
    canvas.height = cssH * dpr;
    const ctx = canvas.getContext('2d');
    ctx.setTransform(dpr, 0, 0, dpr, 0, 0);
    ctx.clearRect(0, 0, cssW, cssH);

    const pts = points.map((p) => ({ lat: p.lat, lng: p.lng }));
    if (fix) pts.push({ lat: fix.lat, lng: fix.lng });
    if (!pts.length) {
      ctx.fillStyle = '#8a8f98';
      ctx.font = '15px system-ui';
      ctx.textAlign = 'center';
      ctx.fillText('Start GPS and mark points — they plot here.', cssW / 2, cssH / 2);
      return;
    }

    // fit bounding box, 12% padding, equal axis scale
    const lats = pts.map((p) => p.lat), lngs = pts.map((p) => p.lng);
    const minLat = Math.min(...lats), maxLat = Math.max(...lats);
    const minLng = Math.min(...lngs), maxLng = Math.max(...lngs);
    const midLat = (minLat + maxLat) / 2;
    const spanX = (Math.max(maxLng - minLng, 1e-6)) * Math.cos((midLat * Math.PI) / 180) * 111320;
    const spanY = Math.max(maxLat - minLat, 1e-6) * 110540;
    const pad = 28;
    const scale = Math.min((cssW - 2 * pad) / spanX, (cssH - 2 * pad) / spanY);
    const offX = (cssW - spanX * scale) / 2;
    const offY = (cssH - spanY * scale) / 2;
    const px = (p) => [
      offX + ((p.lng - minLng) * Math.cos((midLat * Math.PI) / 180) * 111320) * scale,
      cssH - offY - ((p.lat - minLat) * 110540) * scale, // lat grows up
    ];

    // polygon / path
    if (pts.length >= 2 && points.length >= 2) {
      ctx.beginPath();
      points.forEach((p, i) => (i ? ctx.lineTo(...px(p)) : ctx.moveTo(...px(p))));
      if (closed && points.length >= 3) ctx.closePath();
      ctx.strokeStyle = '#2b6cb0';
      ctx.lineWidth = 2;
      ctx.stroke();
      if (closed && points.length >= 3) {
        ctx.fillStyle = 'rgba(43, 108, 176, 0.12)';
        ctx.fill();
      }
    }

    // marked points, numbered
    points.forEach((p, i) => {
      const [x, y] = px(p);
      ctx.beginPath();
      ctx.arc(x, y, 11, 0, Math.PI * 2);
      ctx.fillStyle = '#2b6cb0';
      ctx.fill();
      ctx.fillStyle = '#fff';
      ctx.font = 'bold 12px system-ui';
      ctx.textAlign = 'center';
      ctx.textBaseline = 'middle';
      ctx.fillText(String(p.seq ?? i + 1), x, y);
    });

    // live fix crosshair
    if (fix) {
      const [x, y] = px(fix);
      ctx.beginPath();
      ctx.arc(x, y, Math.max(4, (fix.accuracy || 5) * scale), 0, Math.PI * 2);
      ctx.fillStyle = 'rgba(214, 140, 28, 0.25)';
      ctx.fill();
      ctx.beginPath();
      ctx.arc(x, y, 5, 0, Math.PI * 2);
      ctx.fillStyle = '#d68c1c';
      ctx.fill();
    }

    // scale bar (nice round meters)
    const targetPx = Math.min(cssW, cssH) * 0.25;
    const rounds = [1, 2, 5, 10, 20, 50, 100, 200, 500];
    const barM = rounds.find((r) => r * scale >= targetPx * 0.6) || 500;
    const bx = 16, by = cssH - 18, bw = barM * scale;
    ctx.strokeStyle = '#444';
    ctx.lineWidth = 2;
    ctx.beginPath(); ctx.moveTo(bx, by); ctx.lineTo(bx + bw, by); ctx.stroke();
    ctx.fillStyle = '#444';
    ctx.font = '12px system-ui';
    ctx.textAlign = 'left';
    ctx.textBaseline = 'bottom';
    ctx.fillText(`${barM} m / ${(barM * M_TO_FT).toFixed(0)} ft`, bx, by - 4);
  }, [points, fix, closed]);

  return <canvas ref={ref} className="plot" />;
}

// ==================== POINT ROW (module scope: keeps input focus) ====================
function PointRow({ point, dist, readOnly, onLabel, onDelete }) {
  return (
    <li className="point-row">
      <span className="seq">{point.seq}</span>
      <input
        className="label"
        defaultValue={point.label}
        placeholder={`point ${point.seq}`}
        disabled={readOnly}
        onBlur={(e) => e.target.value !== point.label && onLabel(point, e.target.value)}
        onKeyDown={(e) => e.key === 'Enter' && e.target.blur()}
      />
      <span className="dist">{fmtDist(dist)}</span>
      <span className={`acc ${accClass(point.accuracy)}`}>
        {point.accuracy != null ? `±${point.accuracy.toFixed(0)} m` : ''}
      </span>
      {!readOnly && (
        <button className="del" onClick={() => onDelete(point)} title="delete point">✕</button>
      )}
    </li>
  );
}

// ==================== MAIN APP ====================
export default function YardMap({ items, onSelect, readOnly = false, compact = false }) {
  const [maps, setMaps] = useState(items || []);
  const [open, setOpen] = useState(null);      // {map, points}
  const [newName, setNewName] = useState('');
  const [closed, setClosed] = useState(false);

  // ---- live GPS ----
  const [watching, setWatching] = useState(false);
  const [fix, setFix] = useState(null);
  const [gpsError, setGpsError] = useState(null);
  const watchId = useRef(null);
  const lastFix = useRef(null);

  const geoSupported = typeof navigator !== 'undefined' && 'geolocation' in navigator;
  const secure = typeof window === 'undefined' || window.isSecureContext ||
    location.hostname === 'localhost' || location.hostname === '127.0.0.1';

  function startWatch() {
    setGpsError(null);
    const id = navigator.geolocation.watchPosition(
      (pos) => {
        const f = {
          lat: pos.coords.latitude, lng: pos.coords.longitude,
          accuracy: pos.coords.accuracy, ts: Date.now(),
        };
        lastFix.current = f;
        setFix(f);
        setGpsError(null);
      },
      (err) => setGpsError(err.message || `code ${err.code}`),
      { enableHighAccuracy: true, maximumAge: 1000, timeout: 20000 }
    );
    watchId.current = id;
    setWatching(true);
  }

  function stopWatch() {
    if (watchId.current != null) navigator.geolocation.clearWatch(watchId.current);
    watchId.current = null;
    setWatching(false);
  }

  useEffect(() => stopWatch, []); // never leak the GPS watch past unmount

  // ---- data ----
  async function loadMaps() {
    if (items) return;
    setMaps(await apiJSON('/api/yard/maps'));
  }
  useEffect(() => { loadMaps().catch((e) => setGpsError(String(e.message || e))); }, [items]);

  async function openMap(m) {
    if (onSelect) return onSelect(m);
    const data = await apiJSON(`/api/yard/maps/${m.id}`);
    setOpen(data);
  }

  async function createMap(e) {
    e.preventDefault();
    if (!newName.trim()) return;
    await apiJSON('/api/yard/maps', {
      method: 'POST', headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ name: newName }),
    });
    setNewName('');
    await loadMaps();
  }

  async function deleteMap(m) {
    await apiJSON(`/api/yard/maps/${m.id}`, { method: 'DELETE' });
    await loadMaps();
  }

  async function markPoint() {
    const f = lastFix.current;
    if (!f || !open) return;
    const p = await apiJSON(`/api/yard/maps/${open.map.id}/points`, {
      method: 'POST', headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ lat: f.lat, lng: f.lng, accuracy: f.accuracy }),
    });
    setOpen({ ...open, points: [...open.points, p] });
  }

  async function relabelPoint(point, label) {
    const p = await apiJSON(`/api/yard/points/${point.id}`, {
      method: 'PATCH', headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ label }),
    });
    setOpen({ ...open, points: open.points.map((x) => (x.id === p.id ? p : x)) });
  }

  async function deletePoint(point) {
    await apiJSON(`/api/yard/points/${point.id}`, { method: 'DELETE' });
    const points = open.points.filter((x) => x.id !== point.id).map((x, i) => ({ ...x, seq: i + 1 }));
    setOpen({ ...open, points });
  }

  function exportCsv() {
    const rows = [['seq', 'label', 'lat', 'lng', 'accuracy_m', 'segment_m']];
    open.points.forEach((p, i) => {
      const seg = i > 0 ? haversine(open.points[i - 1], p) : 0;
      rows.push([p.seq, p.label, p.lat, p.lng, p.accuracy ?? '', seg.toFixed(2)]);
    });
    const blob = new Blob([rows.map((r) => r.join(',')).join('\n')], { type: 'text/csv' });
    const a = document.createElement('a');
    a.href = URL.createObjectURL(blob);
    a.download = `${open.map.name.replace(/[^\w-]+/g, '_')}.csv`;
    a.click();
    URL.revokeObjectURL(a.href);
  }

  // ==================== RENDER: detail ====================
  if (open) {
    const pts = open.points;
    const total = pathLength(pts) + (closed && pts.length >= 3 ? haversine(pts[pts.length - 1], pts[0]) : 0);
    const area = closed && pts.length >= 3 ? polygonArea(pts) : 0;
    return (
      <div className="yardmap-app">
        {!compact && (
          <header className="shell">
            <button className="back" onClick={() => { stopWatch(); setOpen(null); loadMaps().catch(() => {}); }}>← maps</button>
            <h2 className="map-title">{open.map.name}</h2>
          </header>
        )}
        <GpsNotice supported={geoSupported && !readOnly} secure={secure} error={gpsError} />
        <Plot points={pts} fix={watching ? fix : null} closed={closed} />

        {!readOnly && (
          <div className="gps-bar">
            {watching ? (
              <button className="stop" onClick={stopWatch}>■ stop GPS</button>
            ) : (
              <button className="start" disabled={!geoSupported || !secure} onClick={startWatch}>▶ start GPS</button>
            )}
            <button
              className="mark"
              disabled={!watching || !fix}
              onClick={markPoint}
            >＋ mark point {fix ? `(±${fix.accuracy.toFixed(0)} m)` : ''}</button>
          </div>
        )}
        <div className={`live acc ${accClass(fix?.accuracy)}`}>
          {fix ? `fix: ${fix.lat.toFixed(6)}, ${fix.lng.toFixed(6)} — ±${fix.accuracy?.toFixed(1)} m` : 'no fix yet'}
          {pts.length >= 2 ? ' — walk the boundary, one mark per corner' : ''}
        </div>

        <div className="stats">
          <span><b>{pts.length}</b> points</span>
          <span><b>{fmtDist(total)}</b> {closed && pts.length >= 3 ? 'perimeter' : 'path'}</span>
          {closed && area > 0 && <span><b>{fmtArea(area)}</b> area</span>}
          <label className="close-loop">
            <input type="checkbox" checked={closed} onChange={(e) => setClosed(e.target.checked)} />
            close loop
          </label>
        </div>

        <ul className="points">
          {pts.map((p, i) => (
            <PointRow
              key={p.id}
              point={p}
              dist={i > 0 ? haversine(pts[i - 1], p) : 0}
              readOnly={readOnly}
              onLabel={relabelPoint}
              onDelete={deletePoint}
            />
          ))}
        </ul>

        {pts.length > 0 && (
          <button className="export" onClick={exportCsv}>export CSV</button>
        )}
      </div>
    );
  }

  // ==================== RENDER: map list ====================
  return (
    <div className="yardmap-app">
      {!compact && (
        <header className="shell">
          <h2 className="map-title">📐 Yard Map</h2>
          <p className="sub">Walk the boundary with your phone; mark a point at each corner.</p>
        </header>
      )}
      {!readOnly && (
        <form className="new-map" onSubmit={createMap}>
          <input
            value={newName}
            onChange={(e) => setNewName(e.target.value)}
            placeholder="new survey name (e.g. back yard)"
          />
          <button type="submit" disabled={!newName.trim()}>create</button>
        </form>
      )}
      <ul className="maps">
        {maps.map((m) => (
          <li key={m.id} className="map-card">
            <button className="open" onClick={() => openMap(m)}>
              <b>{m.name}</b>
              <span>{m.point_count} points · {new Date(m.updated_at).toLocaleDateString()}</span>
            </button>
            {!readOnly && (
              <button className="del" onClick={() => deleteMap(m)} title="delete survey">✕</button>
            )}
          </li>
        ))}
        {!maps.length && <li className="empty">No surveys yet — create one, then map it from your phone.</li>}
      </ul>
    </div>
  );
}
