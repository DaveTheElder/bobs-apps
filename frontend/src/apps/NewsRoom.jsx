import React, { useState, useEffect, useCallback } from 'react';
import { apiFetch, apiJSON } from '../api';
import './newsroom.css';
import DeskTab from './DeskTab';

// ── §1: Presentational bits ──────────────────────────────────────────

const CATEGORY_SECTIONS = [
  { key: 'world', label: 'World' },
  { key: 'tech', label: 'Technology & AI' },
  { key: 'general', label: 'Briefs' },
  { key: 'alt-press', label: 'Alt Press Radar' },
];

function formatDate(dateStr) {
  if (!dateStr) return '';
  try {
    // Bare YYYY-MM-DD parses as UTC midnight, which lands on the previous
    // evening west of Greenwich — anchor to local noon so the dateline day
    // matches the edition key.
    const bare = /^\d{4}-\d{2}-\d{2}$/.test(dateStr);
    return new Date(bare ? dateStr + 'T12:00:00' : dateStr).toLocaleDateString(undefined, {
      weekday: 'long', year: 'numeric', month: 'long', day: 'numeric',
    });
  } catch {
    return dateStr;
  }
}

// Edition key = the day a story was published (YYYY-MM-DD). Stories with no
// date (manual filings) ride along on the newest edition so they're never
// invisible behind the day filter.
function editionKey(item) {
  return item.published_at ? String(item.published_at).slice(0, 10) : '';
}

// Byline strip shared by cards and the full article.
function Byline({ item }) {
  return (
    <div className="newsroom-byline">
      {item.source ? item.source + ' — ' : ''}
      {formatDate(item.published_at) || item.category || 'general'}
    </div>
  );
}

// The story above the fold: giant headline, dek with drop cap.
function LeadStory({ item, onOpen }) {
  return (
    <article className="newsroom-lead" onClick={onOpen}>
      <span className="newsroom-kicker">Featured</span>
      <h2>{item.title}</h2>
      <p className="newsroom-dek">{item.summary}</p>
      <div style={{ marginTop: '10px' }}>
        <Byline item={item} />
        <span className="newsroom-readmore"> ▸ Full story</span>
      </div>
    </article>
  );
}

// A column story: headline + short summary + byline.
function ColumnStory({ item, onOpen }) {
  return (
    <article className="newsroom-item" onClick={onOpen}>
      <h3>{item.title}</h3>
      <p>{item.summary}</p>
      <Byline item={item} />
      <span className="newsroom-readmore"> ▸ Full story</span>
    </article>
  );
}

// ── §1b: Print edition ───────────────────────────────────────────────
//
// One day rendered as a real front page: everything prints in full (dive
// body where it exists, summary otherwise), nothing is click-gated. Printed
// via window.print() with the @media print rules in newsroom.css (toggled by
// a body class so SPA chrome hides only while this view is up).

function PrintEdition({ items, editionDate, onClose }) {
  const featuredList = items.filter(i => i.featured === 1);
  const lead = featuredList[0] || null;
  const rest = items.filter(i => i !== lead);
  const knownCats = new Set(CATEGORY_SECTIONS.map(s => s.key));
  const sections = CATEGORY_SECTIONS.map(s => ({
    ...s,
    stories: rest.filter(i => (knownCats.has(i.category) ? i.category === s.key
      : s.key === 'general' && !knownCats.has(i.category))),
  })).filter(s => s.stories.length > 0);

  return (
    <div className="newsroom-print-page">
      <div className="newsroom-print-controls newsroom-no-print">
        <button onClick={onClose}>× Back to edition</button>
        <button className="newsroom-file-btn" onClick={() => window.print()}>🖨 Print this edition</button>
        <span className="newsroom-print-hint">or just Ctrl+P — saves clean to PDF</span>
      </div>

      <div className="newsroom-print-sheet">
        <div className="newsroom-masthead">
          <h1>The Morning Brief</h1>
        </div>
        <div className="newsroom-dateline">
          <span>{formatDate(editionDate)}</span>
          <span>{items.length} {items.length === 1 ? 'story' : 'stories'} · Final Edition</span>
        </div>

        {lead && (
          <article className="newsroom-print-lead">
            <span className="newsroom-kicker">Featured</span>
            <h2>{lead.title}</h2>
            <div className="newsroom-byline">
              {lead.source ? lead.source + ' — ' : ''}{formatDate(lead.published_at)}
            </div>
            <div className="newsroom-print-body">{lead.content || lead.summary}</div>
          </article>
        )}

        <div className="newsroom-print-cols">
          {sections.map(section => (
            <section key={section.key} className="newsroom-print-section">
              <h4 className="newsroom-section-head">{section.label}</h4>
              {section.stories.map(item => (
                <article key={item.id} className="newsroom-print-story">
                  <h3>{item.title}</h3>
                  <div className="newsroom-print-body">{item.content || item.summary}</div>
                  {item.url ? (
                    <div className="newsroom-print-src">
                      Source: {item.source || (() => { try { return new URL(item.url).hostname; } catch { return ''; } })()} —{' '}
                      <a href={item.url}>{item.url}</a>
                    </div>
                  ) : (
                    item.source && <div className="newsroom-print-src">Source: {item.source}</div>
                  )}
                </article>
              ))}
            </section>
          ))}
        </div>

        <div className="newsroom-print-footer">
          The Morning Brief · compiled from the wire by local intelligence · not for distribution past the kitchen table
        </div>
      </div>
    </div>
  );
}

// The full-article (deep dive) view. Falls back to the summary when a story
// has no dive body — a blank column is worse than a reprinted dek.
function FullArticle({ item, onClose, editable, onUpdate, onDelete }) {
  let host = '';
  try { if (item.url) host = new URL(item.url).hostname; } catch { /* malformed URL: no link */ }
  return (
    <article className="newsroom-article">
      <span className="newsroom-kicker">{item.category || 'general'}</span>
      <h2>{item.title}</h2>
      <Byline item={item} />
      <hr className="newsroom-article-hr" />
      <div className="newsroom-article-body">
        {item.content || item.summary || 'No article content yet.'}
      </div>
      {host && (
        <a className="newsroom-original-link" href={item.url} target="_blank" rel="noopener noreferrer">
          ↗ Source: {host}
        </a>
      )}
      <div className="newsroom-article-actions newsroom-actions">
        {editable && (
          <button onClick={onUpdate}>✎ File correction</button>
        )}
        {editable && (
          <button className="newsroom-danger" onClick={onDelete}>🗑 Kill story</button>
        )}
        <button onClick={onClose}>× Back to edition</button>
      </div>
    </article>
  );
}

// ── §2: Form (add / edit) ────────────────────────────────────────────

function NewsForm({ initial, onSubmit, loading }) {
  const [title, setTitle] = useState(initial?.title || '');
  const [summary, setSummary] = useState(initial?.summary || '');
  const [content, setContent] = useState(initial?.content || '');
  const [source, setSource] = useState(initial?.source || '');
  const [url, setUrl] = useState(initial?.url || '');
  const [category, setCategory] = useState(initial?.category || 'general');
  const [featured, setFeatured] = useState(initial?.featured ? true : false);
  const [publishedAt, setPublishedAt] = useState(initial?.published_at || '');
  const [error, setError] = useState('');

  async function handleSubmit(e) {
    e.preventDefault();
    setError('');
    if (!title.trim()) { setError('Headline is required'); return; }
    if (!summary.trim()) { setError('Summary is required'); return; }

    const body = {
      title: title.trim(),
      summary: summary.trim(),
      content,
      source: source.trim(),
      url: url.trim(),
      category: category.trim() || 'general',
      featured,
      published_at: publishedAt || null,
    };

    try {
      await onSubmit(body);
    } catch (err) {
      setError(err.message || 'Save failed');
    }
  }

  const cellStyle = { display: 'flex', flexDirection: 'column', gap: '4px' };

  return (
    <div className="newsroom-form">
      <h3>{initial ? 'File correction' : 'File a story'}</h3>
      {error && <div className="newsroom-error">{error}</div>}
      <form onSubmit={handleSubmit} style={{ display: 'flex', flexDirection: 'column', gap: '12px' }}>
        <div style={{ display: 'flex', gap: '16px', flexWrap: 'wrap', alignItems: 'flex-end' }}>
          <div style={{ ...cellStyle, flex: 1, minWidth: '240px' }}>
            <label>Headline *</label>
            <input type="text" value={title} onChange={(e) => setTitle(e.target.value)} />
          </div>
          <div style={cellStyle}>
            <label>Front page</label>
            <input type="checkbox" checked={featured} onChange={(e) => setFeatured(e.target.checked)}
              style={{ width: '18px', height: '18px', marginBottom: '6px' }} />
          </div>
        </div>
        <div style={cellStyle}>
          <label>Summary *</label>
          <textarea value={summary} onChange={(e) => setSummary(e.target.value)} rows={3}
            style={{ resize: 'vertical' }} />
        </div>
        <div style={cellStyle}>
          <label>Full article</label>
          <textarea value={content} onChange={(e) => setContent(e.target.value)} rows={6}
            placeholder="The deep dive — printed when someone opens this story."
            style={{ resize: 'vertical' }} />
        </div>
        <div style={{ display: 'flex', gap: '16px', flexWrap: 'wrap' }}>
          <div style={{ ...cellStyle, flex: 1, minWidth: '200px' }}>
            <label>Source</label>
            <input type="text" value={source} onChange={(e) => setSource(e.target.value)} placeholder="e.g. The Daily" />
          </div>
          <div style={{ ...cellStyle, flex: 1, minWidth: '200px' }}>
            <label>Section</label>
            <input type="text" value={category} onChange={(e) => setCategory(e.target.value)} placeholder="general" />
          </div>
        </div>
        <div style={{ display: 'flex', gap: '16px', flexWrap: 'wrap' }}>
          <div style={{ ...cellStyle, flex: 1, minWidth: '260px' }}>
            <label>Source URL</label>
            <input type="url" value={url} onChange={(e) => setUrl(e.target.value)} placeholder="https://example.com/story" />
          </div>
          <div style={{ ...cellStyle, flex: 1, minWidth: '180px' }}>
            <label>Published at</label>
            <input type="datetime-local" value={publishedAt} onChange={(e) => setPublishedAt(e.target.value)} />
          </div>
        </div>
        <div className="newsroom-actions" style={{ display: 'flex', gap: '10px', justifyContent: 'flex-end', marginTop: '8px' }}>
          <button type="button" onClick={() => onSubmit(null)}>Cancel</button>{/* null signals cancel */}
          <button type="submit" disabled={loading} style={loading ? { opacity: 0.5, cursor: 'wait' } : undefined}>
            {loading ? 'Filing…' : (initial ? 'Save changes' : 'Publish')}
          </button>
        </div>
      </form>
    </div>
  );
}

// ── §3: Main NewsRoom component ──────────────────────────────────────

/**
 * NewsRoom — props (all optional; standalone works with none):
 *   items        Pre-loaded news rows. When set, the component never fetches.
 *   onSelect(item)  Called when a user opens a deep dive (host owns display).
 *   readOnly     Hide add/edit/delete chrome — for embedding in read-only contexts.
 *   compact      Skip the masthead — for embedding inside another page.
 */
export default function NewsRoom({ items: propsItems, onSelect, readOnly, compact }) {
  const [items, setItems] = useState(propsItems || null);   // null = not yet loaded / fetch mode
  const [openId, setOpenId] = useState(null);              // which story is open
  const [editingId, setEditingId] = useState(null);        // which row is being edited
  const [adding, setAdding] = useState(false);             // add-form visible?
  const [loading, setLoading] = useState(!propsItems);     // fetch unless items passed in
  const [error, setError] = useState('');
  const [editionIdx, setEditionIdx] = useState(0);         // 0 = newest edition
  const [view, setView] = useState('edition');             // 'edition' | 'desk'
  const [printOpen, setPrintOpen] = useState(false);       // print-preview overlay

  // While the print preview is up, mark <body> so @media print rules can hide
  // SPA chrome (header/window shadow/tabs) without leaking into other apps.
  useEffect(() => {
    if (!printOpen) return undefined;
    document.body.classList.add('newsroom-printing');
    return () => document.body.classList.remove('newsroom-printing');
  }, [printOpen]);

  // Fetch once in standalone mode. Embed mode (items provided) skips the network.
  useEffect(() => {
    if (propsItems !== undefined) return;
    let cancelled = false;
    async function load() {
      try {
        const data = await apiJSON('/api/news');
        if (!cancelled) setItems(data.news || []);
      } catch (e) {
        if (!cancelled) setError(e.message || 'Failed to load news');
      } finally {
        if (!cancelled) setLoading(false);
      }
    }
    load();
    return () => { cancelled = true; };
  }, [propsItems]);

  // ── mutations ──────────────────────────────────────────────────────

  const createItem = useCallback(async (body) => {
    if (body === null) { setAdding(false); return; } // cancel
    const res = await apiFetch('/api/news', {
      method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(body),
    });
    if (!res.ok) { const d = await res.json().catch(() => ({})); throw new Error(d.error || 'Create failed'); }
    const created = await res.json();
    setItems(prev => (prev ? [created, ...prev] : [created]));
    setAdding(false);
  }, []);

  const updateItem = useCallback(async (id, body) => {
    if (body === null) { setEditingId(null); return; } // cancel
    const res = await apiFetch(`/api/news/${id}`, {
      method: 'PUT', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(body),
    });
    if (!res.ok) { const d = await res.json().catch(() => ({})); throw new Error(d.error || 'Update failed'); }
    const updated = await res.json();
    setItems(prev => prev ? prev.map(i => i.id === id ? updated : i) : prev);
    setEditingId(null);
    setOpenId(id);
  }, []);

  const deleteItem = useCallback(async (id) => {
    if (!window.confirm('Kill this story?')) return;
    const res = await apiFetch(`/api/news/${id}`, { method: 'DELETE' });
    if (!res.ok) { const d = await res.json().catch(() => ({})); throw new Error(d.error || 'Delete failed'); }
    setItems(prev => prev ? prev.filter(i => i.id !== id) : prev);
    if (openId === id) setOpenId(null);
  }, [openId]);

  // ── render ─────────────────────────────────────────────────────────

  const all = items || [];

  // Editions = the distinct publication days present, newest first. One day
  // prints at a time like an actual paper; undated stories join the newest
  // edition. editionIdx is clamped so deleting the last story of an edition
  // can't leave the pager pointing at a phantom day.
  const editions = [...new Set(all.map(editionKey).filter(Boolean))].sort().reverse();
  const maxIdx = Math.max(0, editions.length - 1);
  const idx = Math.min(editionIdx, maxIdx);
  const currentKey = editions[idx] || null;
  const list = currentKey
    ? all.filter(i => editionKey(i) === currentKey || !editionKey(i))
    : all;

  // Lead = newest featured story (API already sorts featured DESC, published
  // DESC). Everything else groups into sections; stories whose category has
  // no section (or empty ones) fold into Briefs so nothing goes unprinted.
  const featuredList = list.filter(i => i.featured === 1);
  const lead = featuredList[0] || null;
  const pool = list.filter(i => i !== lead);
  const knownCats = new Set(CATEGORY_SECTIONS.map(s => s.key));
  const sections = CATEGORY_SECTIONS.map(s => ({
    ...s,
    stories: pool.filter(i => (knownCats.has(i.category) ? i.category === s.key
      : s.key === 'general' && !knownCats.has(i.category))),
  })).filter(s => s.stories.length > 0);

  // Embedded mode: hand the open item to the host instead of rendering inline.
  if (onSelect && openId) {
    const item = list.find(i => i.id === openId);
    if (item) onSelect(item);
    return null; // host renders the deep dive
  }

  const openItem = openId ? list.find(i => i.id === openId) : null;
  const editable = !readOnly;

  const masthead = !compact && (
    <>
      <div className="newsroom-masthead">
        <h1>The Morning Brief</h1>
      </div>
      <div className="newsroom-dateline">
        <span>{formatDate(currentKey || new Date().toISOString())}</span>
        {/* Edition pager: pages through the days that actually have stories. */}
        {editions.length > 1 && (
          <span className="newsroom-edition-nav">
            <button className="newsroom-nav-btn" disabled={idx >= maxIdx}
              onClick={() => { setEditionIdx(idx + 1); setOpenId(null); }} aria-label="Previous edition">‹</button>
            <span>Edition {idx + 1} of {editions.length}</span>
            <button className="newsroom-nav-btn" disabled={idx === 0}
              onClick={() => { setEditionIdx(idx - 1); setOpenId(null); }} aria-label="Next edition">›</button>
          </span>
        )}
        <span>{list.length} {list.length === 1 ? 'story' : 'stories'} · Vol. I</span>
      </div>
    </>
  );

  const toolbar = editable && !openItem && !adding && (
    <div className="newsroom-toolbar">
      <button className="newsroom-file-btn"
        onClick={() => { setAdding(true); setEditingId(null); setOpenId(null); }}>
        + File a story
      </button>
      {list.length > 0 && (
        <button className="newsroom-file-btn" onClick={() => setPrintOpen(true)}>
          🖨 Print edition
        </button>
      )}
    </div>
  );

  const form = (adding || editingId) && (
    <NewsForm
      initial={editingId ? list.find(i => i.id === editingId) : null}
      onSubmit={editingId ? (b) => updateItem(editingId, b) : createItem}
      loading={loading}
    />
  );

  if (loading && list.length === 0) {
    return (
      <div className="newsroom-paper" style={{ textAlign: 'center', fontStyle: 'italic' }}>
        <p>Setting today&rsquo;s edition&hellip;</p>
      </div>
    );
  }

  if (error) {
    return (
      <div className="newsroom-paper">
        <p className="newsroom-kicker">Press room error</p>
        <p>{error}</p>
      </div>
    );
  }

  if (printOpen && currentKey) {
    return (
      <PrintEdition
        items={list}
        editionDate={currentKey}
        onClose={() => setPrintOpen(false)}
      />
    );
  }

  const deskOn = view === 'desk';

  return (
    <div className="newsroom-paper">
      {masthead}
      {/* Edition vs Newsroom Desk (reporter roster + chat). Desk owns its own
          data path (/api/news/beats*); nothing here fetches for it. */}
      <div className="desk-tabs" role="tablist">
        <button role="tab" aria-selected={!deskOn}
          className={`desk-tab${deskOn ? '' : ' desk-tab-active'}`}
          onClick={() => setView('edition')}>Edition</button>
        <button role="tab" aria-selected={deskOn}
          className={`desk-tab${deskOn ? ' desk-tab-active' : ''}`}
          onClick={() => setView('desk')}>Newsroom Desk</button>
      </div>

      {deskOn ? (
        <DeskTab />
      ) : (
        <>
      {toolbar}

      {openItem ? (
        <FullArticle
          item={openItem}
          onClose={() => setOpenId(null)}
          editable={editable}
          onUpdate={() => { setEditingId(openItem.id); setOpenId(null); }}
          onDelete={() => deleteItem(openItem.id)}
        />
      ) : (
        <>
          {lead && (
            <LeadStory item={lead} onOpen={() => setOpenId(lead.id)} />
          )}
          {sections.map(section => (
            <section key={section.key}>
              <h4 className="newsroom-section-head">{section.label}</h4>
              <div className="newsroom-columns">
                {section.stories.map(item => (
                  <ColumnStory key={item.id} item={item} onOpen={() => setOpenId(item.id)} />
                ))}
              </div>
            </section>
          ))}
          {list.length === 0 && (
            <p style={{ fontStyle: 'italic', color: '#5c564d', padding: '20px 0' }}>
              No stories filed. The presses are cold — add one to start the edition.
            </p>
          )}
        </>
      )}
        </>
      )}

      {!deskOn && form}
    </div>
  );
}
