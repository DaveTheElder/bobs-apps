/**
 * frontend/src/apps/NewsRoom.jsx — News room app: daily summaries + deep dives.
 *
 * Contract:
 *   • Default (standalone): fetches from /api/news, renders a broadsheet-style
 *     edition where clicking a story opens the full deep dive inline.
 *   • Embeddable: accepts `items` (pre-loaded rows), `onSelect(item)` (host
 *     decides what to do with a deep dive), `readOnly` (hide add/edit/delete
 *     chrome), and `compact` (skip the masthead). When `items` is provided the
 *     component never hits the network — the host owns the data.
 *   • All mutating endpoints go through ../api (apiFetch/apiJSON) so the base
 *   URL resolves the same way whether served at :8080 or under /pages/*.
 *
 * One story = one row: summary for the headline view, content for the deep
 * dive. One day prints at a time (an "edition" per publication date, newest
 * first, paged from the dateline). The newest featured story of the current
 * edition runs above the fold; the rest are grouped into category "sections"
 * (world / tech / general / alt-press) laid out in newspaper columns. Visual
 * skin lives in newsroom.css, fully scoped under .newsroom-paper so it can't
 * leak into sibling apps.
 */

